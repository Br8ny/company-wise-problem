#!/usr/bin/env python3
"""Build a searchable index from the per-company CSV lists.

Reads every ``<Company>/<window>.csv`` file and emits:

* ``index/companies.json``  - machine-readable per-company stats
* ``INDEX.md``              - markdown summary table (top companies + totals)

Usage:
    python scripts/build_index.py          # run from the repository root
"""
from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WINDOWS = ["Thirty Days", "Three Months", "Six Months", "More Than Six Months", "All"]
DIFFICULTIES = ("EASY", "MEDIUM", "HARD")


def slug(name: str) -> str:
    return name.strip().lower().replace(" ", "-")


def load_window(path: Path) -> list[dict]:
    rows: list[dict] = []
    if not path.exists():
        return rows
    with path.open(encoding="utf-8-sig", newline="") as fh:
        for raw in csv.DictReader(fh):
            title = (raw.get("Title") or "").strip()
            if not title:
                continue
            try:
                frequency = round(float(raw.get("Frequency") or 0.0), 2)
            except ValueError:
                frequency = 0.0
            try:
                acceptance = round(float(raw.get("Acceptance Rate") or 0.0) * 100, 2)
            except ValueError:
                acceptance = 0.0
            rows.append(
                {
                    "title": title,
                    "difficulty": (raw.get("Difficulty") or "").strip().upper(),
                    "frequency": frequency,
                    "acceptance": acceptance,
                    "link": (raw.get("Link") or "").strip(),
                    "topics": [
                        t.strip() for t in (raw.get("Topics") or "").split(",") if t.strip()
                    ],
                }
            )
    return rows


def main() -> None:
    companies: dict[str, dict] = {}
    grand_total = 0
    difficulty_totals: Counter[str] = Counter()

    for folder in sorted(p for p in ROOT.iterdir() if p.is_dir()):
        if folder.name.startswith(".") or folder.name in {"index", "scripts"}:
            continue
        windows = {
            w: load_window(next(folder.glob(f"*. {w}.csv"), folder / "__missing__"))
            for w in WINDOWS
        }
        all_rows = windows["All"]
        seen = {r["title"] for r in all_rows}
        difficulties = Counter(r["difficulty"] for r in all_rows)
        difficulty_totals.update(difficulties)
        grand_total += len(seen)
        companies[folder.name] = {
            "name": folder.name,
            "slug": slug(folder.name),
            "total": len(seen),
            "windows": {w: len(rows) for w, rows in windows.items()},
            "difficulty": {d: difficulties.get(d, 0) for d in DIFFICULTIES},
            "top": sorted(all_rows, key=lambda r: r["frequency"], reverse=True)[:5],
        }

    out_dir = ROOT / "index"
    out_dir.mkdir(exist_ok=True)
    (out_dir / "companies.json").write_text(
        json.dumps({"generated_from": "per-company CSV lists", "companies": companies},
                   indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    ranked = sorted(companies.values(), key=lambda c: c["total"], reverse=True)
    lines = [
        "# Company index",
        "",
        f"Auto-generated by `scripts/build_index.py` — {len(companies)} companies, "
        f"{grand_total} problem entries.",
        "",
        "| # | Company | Total | Easy | Medium | Hard | Last 30 days | All-time list |",
        "|---:|---|---:|---:|---:|---:|---:|---:|",
    ]
    for i, c in enumerate(ranked, start=1):
        d = c["difficulty"]
        lines.append(
            f"| {i} | [{c['name']}](./{c['name'].replace(' ', '%20')}) "
            f"| {c['total']} | {d['EASY']} | {d['MEDIUM']} | {d['HARD']} "
            f"| {c['windows']['Thirty Days']} | {c['windows']['All']} |"
        )
    lines += [
        "",
        "## Totals",
        "",
        f"- Problems listed across all companies: **{grand_total}**",
        f"- By difficulty: EASY {difficulty_totals['EASY']}, "
        f"MEDIUM {difficulty_totals['MEDIUM']}, HARD {difficulty_totals['HARD']}",
        "",
        "Counts are unique titles per company, so the same problem appearing for "
        "several companies is counted once per company.",
        "",
    ]
    (ROOT / "INDEX.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"indexed {len(companies)} companies, {grand_total} entries")


if __name__ == "__main__":
    main()
